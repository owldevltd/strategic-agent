// One readable line per event for the live log, with a tone: "no" for refusals and walls, "ok" for what was
// proven or sent, "wait" for what waits for a person.

app.define( 'Ui.Describe', [], () => class Describe {

	static event( event ) {
		const _d = event.data || {};
		const _lines = {
			coreStarted: () => [ `core started (sandbox ${_d.runtime}, model ${_d.provider})` ],
			gateStarted: () => [ 'gate started' ],
			nodeCreated: () => [ `new goal: ${_d.contract.goal}` ],
			stateChanged: () => [ `${event.node} → ${_d.to}${_d.strategy ? ` (${_d.strategy})` : ''}${_d.reason ? ` · ${_d.reason}` : ''}` ],
			check: () => [ `${_d.gate} ${_d.ok ? 'passed' : `refused: ${( _d.problems || [] ).join( '; ' )}`}`, _d.ok ? '' : 'no' ],
			strategyScored: () => [ `strategies: ${_d.scored.map( item => `${item.id} ${item.reason ? `(${item.reason})` : `${item.points} pts`}` ).join( ' · ' )}` ],
			sandboxStarted: () => [ `sandbox started (${_d.runtime}${_d.isolated ? '' : ', not isolated'})` ],
			sandboxFinished: () => [ `sandbox finished, exit ${_d.exitCode}, ${_d.ms} ms` ],
			sandboxDestroyed: () => [ 'sandbox destroyed' ],
			softRework: () => [ `rework: ${( _d.broken || [] ).map( item => item.says ).join( ' ' )}`, 'wait' ],
			codeRepair: () => [ `the agent's code failed in its frame; one repair, the model hears only: ${( _d.broken || [] ).map( item => item.says ).join( ' ' )}`, 'wait' ],
			sandboxProbesStarted: () => [ `ESCAPE TEST: attacker code in the sandbox (${_d.runtime}${_d.engine ? `, ${_d.engine}` : ''}), ${_d.of} tries`, 'wait' ],
			sandboxProbe: () => [ `${_d.probe}: ${_d.ok ? 'stopped' : 'ESCAPED'} (exit ${_d.exit}, ${_d.ms} ms)${_d.saw ? ` · ${_d.saw}` : ''}`, _d.ok ? 'ok' : 'no' ],
			sandboxProbesEnded: () => [ `escape test: ${_d.stopped} of ${_d.of} stopped; every container destroyed`, _d.stopped === _d.of ? 'ok' : 'no' ],
			value: () => [ `value ${_d.name}: labels [${( _d.labels || [] ).join( ', ' )}]${_d.groupSize !== null ? `, group of ${_d.groupSize}` : ''}` ],
			aiAnswered: () => [ `model (${_d.role}, ${_d.provider}) answered${_d.ok ? '' : ` against its contract: ${_d.problems.join( '; ' )}`}`, _d.ok ? '' : 'no' ],
			wall: () => [ `wall: ${_d.cause}`, 'no' ],
			verdict: () => [ `verdict ${_d.rule}: ${_d.verdict}${_d.overruled ? ` (the model proposed ${_d.proposed}: OVERRULED)` : ''}${_d.open.length ? ` · open: ${_d.open.join( ', ' )}` : ''}` ],
			factDelivered: () => [ `fact: ${_d.kind} (${_d.evidenceClass})`, _d.kind === 'delivered' ? 'ok' : '' ],
			contractProposed: () => [ `goal proposed, waits for a person${_d.goal ? `: ${_d.goal}` : ''}`, 'wait' ],
			contractConfirmed: () => [ `goal and rules confirmed by ${_d.by}`, 'ok' ],
			contractWithdrawn: () => [ 'goal withdrawn before anyone confirmed it', '' ],
			knowledgeForgotten: () => [ `fresh start: earlier runs forgotten (${_d.lessons} lessons, ${_d.gates} strategy gates, ${_d.proposals} proposals)`, '' ],
			refused: () => [ `BLOCKED ${_d.action} → ${_d.target || ''}: ${( _d.reasons || [] ).map( item => item.reason ).join( '; ' )}`, 'no' ],
			awaitingApproval: () => [ `waits for approval: ${_d.summary.action} → ${_d.summary.target}`, 'wait' ],
			approved: () => [ `approved by ${_d.by}`, 'ok' ],
			executed: () => [ `SENT, receipt ${_d.receipt?.id || ''}`, 'ok' ],
			withdrawn: () => [ 'withdrawn', 'no' ],
			concernsRead: () => [ `the message holds ${_d.concerns} concern(s)${_d.dropped ? `, ${_d.dropped} outside the schema dropped` : ''}` ],
			inboundCase: () => [ `NEW CASE from ${_d.from}: ${String( _d.concern?.intent || '' ).replace( /_/g, ' ' )} (foreign, a claim)`, 'wait' ],
			casesStarted: () => [ `${_d.cases.length} case(s) of their own started` ],
			planAccepted: () => [ `round started: ${_d.strategy} (start token burnt)` ],
			reviewDue: () => [ `review of ${_d.strategy} after t_signal`, 'wait' ],
			processStarted: () => [ `a proposed ${_d.kind} runs as its own process: ${_d.id}`, 'wait' ],
			processEnded: () => [ `proposal process ended: ${_d.result}`, _d.result === 'fulfilled' ? 'ok' : 'no' ],
			strategyProposed: () => [ `the model proposes a new strategy: ${_d.strategy?.steps?.map( step => step.move ).join( ' → ' ) || ''}` ],
			catalogExtended: () => [ `catalog extended: ${_d.kind} ${_d.id}, approved by ${_d.by}`, 'ok' ],
			contractAmended: () => [ `the client changed the goal by ticket (${_d.by})`, 'ok' ],
			amendmentRefused: () => [ `change of the goal refused at G1: ${_d.problems.join( '; ' )}`, 'no' ],
			strategyGateAdded: () => [ `strategy gate set: ${_d.rule}` ],
			strategyGateTightened: () => [ `strategy gate tightened: ${_d.rule}` ],
			strategyGateRefused: () => [ `strategy gate refused (only tighter allowed): ${_d.problems.join( '; ' )}`, 'no' ],
			strategyGateLifted: () => [ `strategy gate lifted by ${_d.by}`, 'ok' ],
			tokenConsumed: () => [ 'approval token presented under a valid lease and consumed', 'ok' ],
			redeemRefused: () => [ `approval token refused: ${( _d.reasons || [] ).map( item => item.reason ).join( '; ' )}`, 'no' ],
			credited: () => [ `${_d.criterion} met first by attempt ${_d.attempt}${_d.inTime ? '' : ' (after its deadline: no credit)'}`, 'ok' ],
			lessonWritten: () => [ `lesson written: ${_d.strategy} → ${_d.result}` ],
			lessonCorrected: () => [ `lesson corrected (${_d.reason})` ],
			lateSignal: () => [ `late signal for attempt ${_d.attempt}`, 'ok' ],
			diagnosisLearned: () => [ `learned: wall ${_d.cause} → ${_d.class} (${_d.by})`, 'ok' ],
			questionFromChild: () => [ `a child resembles its parent; the parent says: ${_d.answer}` ],
			knowledgeQuarantined: () => [ `G5: knowledge file into quarantine (${_d.problem})`, 'no' ],
			proposalChecked: () => [ `proposal checked: ${_d.result}`, _d.result === 'green' ? 'ok' : 'no' ],
			baselineSent: () => [ `NEIGHBOUR OFFICE sent: "${_d.body}"`, 'no' ],
			ticketOpened: () => [ `asks a person: ${_d.question}`, 'wait' ],
			ticketAnswered: () => [ `${_d.by} decided: ${_d.choice}`, 'ok' ],
			contractDerived: () => [ `child goal confirmed by derivation (keeps every rule of ${_d.parent})`, 'ok' ],
			taskReceived: () => [ `task: "${_d.task}"`, 'wait' ],
			draftChecked: () => [ `G1 draft ${_d.round}: ${_d.ok ? 'passed' : `refused: ${_d.problems.join( '; ' )}`}`, _d.ok ? 'ok' : 'no' ],
			draftRefused: () => [ `draft refused: ${_d.problems.join( '; ' )}`, 'no' ],
			error: () => [ `error: ${_d.message}`, 'no' ],
			alarm: () => [ `ALARM: an error in the core; the goal is aborted and a person is told (${_d.reason})`, 'no' ],
			moveOutlastsClose: () => [ `${_d.move} still runs after Δ; its lease ends it`, 'wait' ],
			expectationCreated: () => [ `expects ${_d.need} × ${_d.fact} from ${_d.from} until ${_d.until.slice( 11, 19 )}, key ${_d.keys.join( ', ' )}`, 'wait' ],
			waitingFor: () => [ `waits for answers from ${_d.from} (${_d.need} needed)`, 'wait' ],
			waitEnded: () => [ `waiting ended: ${_d.status}, ${_d.count} of ${_d.need}`, _d.status === 'met' ? 'ok' : 'no' ],
			inboundReceived: () => [ `INBOUND from ${_d.from}${_d.subject ? `: "${_d.subject}"` : ''} (its own process, foreign)`, 'wait' ],
			inboundMatchedByModel: () => [ `no key: the model matched it ${_d.expectation ? 'to an open expectation' : 'to nothing'}` ],
			inboundRead: () => [ `read into fixed fields (${_d.fields.join( ', ' )}), evidence class ${_d.evidenceClass}` ],
			inboundNewCase: () => [ 'matches nothing that waits: a new case of its own' ],
			inboundAlsoAsks: () => [ 'the answer also asks for something else: that part is a new case of its own' ],
			factQueued: () => [ `fact ${_d.kind} for the node${_d.late ? ' (LATE, still valid)' : ''}`, 'ok' ],
			worldReplied: () => [ `${_d.from} replies: "${_d.subject}"` ],
			worldReceived: () => [ `the ${_d.team} team got an invitation` ],
			abortReceived: () => [ `ABORT: ${_d.reason}`, 'no' ],
			outsideCleared: () => [ `outside actions cleared: ${_d.deliveries.map( item => item.status ).join( ', ' ) || 'none open'}` ],
			leaseGranted: () => [ `lease ${_d.fence} for ${_d.move}` ],
			leaseExpired: () => [ `LEASE EXPIRED: ${_d.move} ended, its result discarded`, 'no' ],
			resumed: () => [ `resumed after a restart in state ${_d.state}`, 'wait' ],
			runResumed: () => [ `restart: goal ${_d.root} continues from the log`, 'wait' ],
			runNotResumed: () => [ `restart: a goal stays where it is (${_d.reason})`, 'no' ],
			logDamaged: () => [ `restart: ${_d.count} event(s) in the log cannot be read; their goals stay where they are`, 'no' ],
			moveCancelled: () => [ `${_d.move} taken back: ${_d.because}`, 'ok' ],
			lessonsQuarantined: () => [ `G5: ${_d.lessons.length} lesson(s) into quarantine (${_d.lessons[ 0 ]?.problem || ''})`, 'no' ],
			conflict: () => [ `CONFLICT about ${_d.about}: facts of different origins disagree`, 'no' ],
			escalatedToParent: () => [ `stuck, handed back to the parent goal`, 'no' ],
			gatesParalysis: () => [ `the agent's own strategy gates block every plan: ${_d.blocking.join( '; ' )}`, 'no' ],
			calibrationSample: () => [ `sample check of ${_d.role}: ${_d.choice} (${_d.wrong} wrong of ${_d.checked})`, _d.choice === 'right' ? 'ok' : 'no' ],
			attemptFailed: () => [ `attempt ${_d.nr} failed, the gate tries again with the same key`, 'wait' ],
			unclear: () => [ `UNCLEAR whether it took effect: a person checks`, 'no' ],
			notSent: () => [ 'not sent', 'no' ],
			proposalReceived: () => [ `the agent proposes ${_d.kind === 'action' ? 'the action' : 'the master-data value'} ${_d.name} (kind ${_d.scope}); a person decides at the gate`, 'wait' ],
			proposalApproved: () => [ `${_d.name} approved at the gate by ${_d.by}`, 'ok' ],
			proposalRejected: () => [ `${_d.name} rejected at the gate`, 'no' ],
			proposalRevoked: () => [ `${_d.name} taken back at the gate`, 'no' ],
			gateProposalSubmitted: () => [ `asks the gate's operator for ${_d.name}`, 'wait' ],
			gateProposalRefused: () => [ `the gate refused the proposal: ${_d.reason}`, 'no' ],
			channelsLoaded: () => [ `channels registered: ${( _d.channels || [] ).map( item => item.name ).join( ', ' )}` ],
			taskKindCreated: () => [ `a new kind of task: ${_d.kind}` ],
			settled: () => [ `a person settled an unclear action: ${_d.result === 'executed' ? 'it took effect' : 'it did not take effect'}`, 'ok' ],
			masterAdded: () => [ `master data added (${_d.kind}, for ${_d.scope === '*' ? 'every goal' : _d.scope})` ],
			masterRevoked: () => [ `master data revoked (${_d.kind}, ${_d.revoked} value(s))`, 'no' ],
			accessLocked: () => [ `too many wrong answers for ${_d.secret}; locked until ${_d.until}`, 'no' ],
			budgetReserved: () => [ `budget reserved for a child: ${_d.amount}` ],
			budgetReturned: () => [ `child budget returned: ${_d.returned}` ],
			ticketWithdrawn: () => [ `question withdrawn` ],
			ticketExpired: () => [ `question expired without an answer`, 'no' ],
		};
		const [ text = '', tone = '' ] = _lines[ Describe.key( event.kind ) ]?.() || [];
		return { text, tone };
	}

	static rule( rule ) {
		const _texts = {
			minGroup: () => `never about fewer than ${rule.k} people`,
			noDifference: () => `no two releases may differ by fewer than ${rule.k} people`,
			exactlyOnce: () => `each ${rule.key} at most once`,
			knownAccount: () => `${rule.param} only from master data`,
			sumMax: () => `total ${rule.param} at most ${rule.max}`,
			humanApproval: () => `a person approves each ${rule.actions.join( ', ' )}`,
			expires: () => `nothing new leaves after ${rule.at.slice( 0, 16 ).replace( 'T', ' ' )} (+ buffer)`,
		};
		return `• ${_texts[ Describe.key( rule.rule ) ]?.() || rule.rule}`;
	}

	// Event and rule names are data in snake_case; the lookup tables use camelCase.
	static key( name ) {
		return name.replace( /_([a-z])/g, ( _all, char ) => char.toUpperCase() );
	}

} );
